"""Export the HTTP API's OpenAPI document and emit TypeScript types for the UI.

Writes packages/schema-ts/openapi.json and packages/schema-ts/src/api.d.ts. The emitter is a
small, deterministic Python translation of the OpenAPI 3.1 schema (no Node toolchain needed, so
`--check` runs inside scripts/check.sh and CI). `--check` fails when either file is stale.
"""

import argparse
import json
import re
import sys
import tempfile
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
PACKAGE = ROOT / "packages" / "schema-ts"
OPENAPI = PACKAGE / "openapi.json"
TYPES = PACKAGE / "src" / "api.d.ts"
MIXSCRIPT_SCHEMA = ROOT / "schemas" / "mixscript-v1.1.json"
MIXSCRIPT_TYPES = PACKAGE / "src" / "mixscript.d.ts"
INDEX_TYPES = PACKAGE / "src" / "index.d.ts"
HEADER = (
    "// Generated by scripts/gen_api_types.py from openapi.json. Do not edit.\n"
    "// Regenerate: uv run python scripts/gen_api_types.py\n\n"
)
Json = dict[str, Any]
INDEX = (
    HEADER.split("\n\n")[0].replace("from openapi.json", "(static re-exports)")
    + '\n\nexport * from "./api";\nexport * from "./mixscript";\n'
)


def build_openapi() -> Json:
    import os

    from mixconsole.server.app import create_app
    from mixconsole.store.workspace import Workspace

    with tempfile.TemporaryDirectory() as folder:
        os.environ["MIXCONSOLE_CACHE_DIR"] = folder
        workspace = Workspace(Path(folder) / "data")
        try:
            return create_app(workspace, "x" * 32).openapi()
        finally:
            workspace.close()


def ts(schema: Json | bool, depth: int = 0) -> str:
    if schema is True or schema == {}:
        return "unknown"
    if not isinstance(schema, dict):
        return "never"
    if "$ref" in schema:
        return str(schema["$ref"]).rsplit("/", 1)[-1]
    if "const" in schema:
        return json.dumps(schema["const"])
    if "enum" in schema:
        return " | ".join(json.dumps(v) for v in schema["enum"])
    for key, glue in (("anyOf", " | "), ("oneOf", " | "), ("allOf", " & ")):
        if key in schema:
            return glue.join(wrap(ts(s, depth)) for s in schema[key])
    kind = schema.get("type")
    if isinstance(kind, list):
        return " | ".join(ts({**schema, "type": k}, depth) for k in kind)
    if kind == "string":
        return "string"
    if kind in ("integer", "number"):
        return "number"
    if kind == "boolean":
        return "boolean"
    if kind == "null":
        return "null"
    if kind == "array":
        items = schema.get("items", {})
        if "prefixItems" in schema:
            return "[" + ", ".join(ts(s, depth) for s in schema["prefixItems"]) + "]"
        return f"{wrap(ts(items, depth))}[]"
    if kind == "object" or "properties" in schema:
        return obj(schema, depth)
    return "unknown"


def wrap(text: str) -> str:
    return f"({text})" if " | " in text or " & " in text else text


def key(name: str) -> str:
    return name if re.fullmatch(r"[A-Za-z_$][A-Za-z0-9_$]*", name) else json.dumps(name)


def obj(schema: Json, depth: int = 0) -> str:
    indent = "  " * (depth + 1)
    props: Json = schema.get("properties", {})
    required = set(schema.get("required", []))
    lines = []
    for name in sorted(props):
        mark = "" if name in required else "?"
        doc = props[name].get("description") if isinstance(props[name], dict) else None
        if doc:
            lines.append(f"{indent}/** {doc.splitlines()[0]} */")
        lines.append(f"{indent}{key(name)}{mark}: {ts(props[name], depth + 1)};")
    extra = schema.get("additionalProperties")
    patterns = schema.get("patternProperties")
    if extra is None and isinstance(patterns, dict) and len(patterns) == 1:
        extra = next(iter(patterns.values()))
    if not lines and isinstance(extra, dict) and extra:
        return f"Record<string, {ts(extra, depth + 1)}>"
    if extra is not None and extra is not False:
        lines.append(f"{indent}[key: string]: {ts(extra, depth + 1)};")
    if not lines:
        return "Record<string, never>" if extra is False else "Record<string, unknown>"
    return "{\n" + "\n".join(lines) + "\n" + "  " * depth + "}"


def content_type(content: Json | None) -> str:
    if not content:
        return "never"
    options = []
    for media, body in sorted(content.items()):
        options.append(ts(body.get("schema", {})) if media == "application/json" else "unknown")
    return " | ".join(sorted(set(options)))


def emit(doc: Json) -> str:
    out = [HEADER]
    schemas: Json = doc.get("components", {}).get("schemas", {})
    out.extend(f"export type {name} = {ts(schemas[name])};\n\n" for name in sorted(schemas))
    out.append("export interface components {\n  schemas: {\n")
    out.extend(f"    {name}: {name};\n" for name in sorted(schemas))
    out.append("  };\n}\n\n")
    paths: list[str] = []
    ops: list[str] = []
    for path in sorted(doc["paths"]):
        methods = []
        for method in sorted(doc["paths"][path]):
            op = doc["paths"][path][method]
            op_id = op["operationId"]
            methods.append(f"    {method}: operations[{json.dumps(op_id)}];")
            params: dict[str, list[str]] = {"path": [], "query": []}
            for p in op.get("parameters", []):
                if p["in"] in params:
                    mark = "" if p.get("required") else "?"
                    params[p["in"]].append(
                        f"        {json.dumps(p['name'])}{mark}: {ts(p.get('schema', {}))};"
                    )
            lines = []
            for where, items in params.items():
                if items:
                    lines.append(f"      {where}: {{\n" + "\n".join(items) + "\n      };")
            body = op.get("requestBody")
            if body:
                req = content_type(body.get("content"))
                mark = "" if body.get("required") else "?"
                lines.append(f"      requestBody{mark}: {req};")
            responses = []
            for status, resp in sorted(op.get("responses", {}).items()):
                responses.append(
                    f"        {json.dumps(status)}: {content_type(resp.get('content'))};"
                )
            lines.append("      responses: {\n" + "\n".join(responses) + "\n      };")
            ops.append(f"  {json.dumps(op_id)}: {{\n" + "\n".join(lines) + "\n  };")
        paths.append(f"  {json.dumps(path)}: {{\n" + "\n".join(methods) + "\n  };")
    out.append("export interface paths {\n" + "\n".join(paths) + "\n}\n\n")
    out.append("export interface operations {\n" + "\n".join(ops) + "\n}\n")
    return "".join(out)


def emit_mixscript() -> str:
    """MixScript v1.1 document types from the canonical JSON Schema (opaque in the API)."""
    schema: Json = json.loads(MIXSCRIPT_SCHEMA.read_text(encoding="utf-8"))
    definitions: Json = {"MixScript": {k: v for k, v in schema.items() if k != "$defs"}}
    definitions.update(schema.get("$defs", {}))
    header = HEADER.replace("from openapi.json", "from schemas/mixscript-v1.1.json")
    return (
        header
        + "".join(
            f"export type {name} = {ts(definitions[name])};\n\n" for name in sorted(definitions)
        ).rstrip()
        + "\n"
    )


def render() -> tuple[str, str]:
    doc = build_openapi()
    return json.dumps(doc, indent=2, sort_keys=True) + "\n", emit(doc)


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true", help="fail if generated files are stale")
    args = parser.parse_args()
    spec, declarations = render()
    if args.check:
        stale = [
            str(path.relative_to(ROOT))
            for path, text in (
                (OPENAPI, spec),
                (TYPES, declarations),
                (MIXSCRIPT_TYPES, emit_mixscript()),
                (INDEX_TYPES, INDEX),
            )
            if not path.is_file() or path.read_text(encoding="utf-8") != text
        ]
        if stale:
            print(
                f"API types drift: {', '.join(stale)}; run: uv run python scripts/gen_api_types.py"
            )
            return 1
        print("API types up to date")
        return 0
    TYPES.parent.mkdir(parents=True, exist_ok=True)
    OPENAPI.write_text(spec, encoding="utf-8")
    TYPES.write_text(declarations, encoding="utf-8")
    MIXSCRIPT_TYPES.write_text(emit_mixscript(), encoding="utf-8")
    INDEX_TYPES.write_text(INDEX, encoding="utf-8")
    print(f"wrote {OPENAPI.relative_to(ROOT)} and {TYPES.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
